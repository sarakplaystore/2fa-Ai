// Writes dist/sw.js after `vite build`: the offline copy of the app.
//
// The cache holds the app's own static files for one build and nothing else.
// No response is ever added to it at runtime, so vault data, codes, exports and
// import files cannot end up on disk through this file — they are not in the
// list below and there is no `put`/`add` call in the fetch handler at all.
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const CACHE_PREFIX = "still-";

// Copied verbatim from public/ by Vite. Only files that exist are listed, so
// the generator also works on a build without them.
const SHELL = [
  "/",
  "/index.html",
  "/manifest.webmanifest",
  "/favicon.svg",
  "/jsqr-LICENSE.txt",
];

const list = (dir, prefix) =>
  existsSync(dir)
    ? readdirSync(dir)
        .filter((name) => !name.startsWith("."))
        .sort()
        .map((name) => prefix + name)
    : [];

const assets = list("dist/assets", "/assets/");
const icons = list("dist/icons", "/icons/").filter((name) =>
  name.endsWith(".png"),
);

// The cache is named after the build: index.html carries the hashed asset URLs
// and the manifest carries the icon list, so any change to the app produces a
// new name, and the old cache is dropped on activation.
const hash = createHash("sha256");
hash.update(readFileSync("dist/index.html"));
if (existsSync("dist/manifest.webmanifest"))
  hash.update(readFileSync("dist/manifest.webmanifest"));
const CACHE = CACHE_PREFIX + hash.digest("hex").slice(0, 16);

const files = [
  ...new Set([
    ...SHELL.filter((path) => existsSync("dist" + path)),
    ...icons,
    ...assets,
  ]),
];

writeFileSync(
  "dist/sw.js",
  `// Generated by scripts/service-worker.js — do not edit.
// Offline support: the files below are fetched once and then served from the
// cache, so the app opens and unlocks with no connection. The list is fixed at
// build time and nothing else is ever cached.
const CACHE = ${JSON.stringify(CACHE)};
const FILES = ${JSON.stringify(files, null, 2)};
// Any navigation that is not itself cached (a deep link, a bookmark) is served
// the app shell instead of an offline error page.
const SHELL = "/index.html";

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(FILES))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith(${JSON.stringify(CACHE_PREFIX)}) && key !== CACHE)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  // Only this origin's files, and only reads. No response is stored here: the
  // cache is the FILES list above and stays that way.
  if (request.method !== "GET") return;
  if (!request.url.startsWith(self.location.origin + "/")) return;
  const navigate = request.mode === "navigate";
  event.respondWith(
    caches
      .open(CACHE)
      .then((cache) =>
        cache
          .match(request, { ignoreVary: true })
          .then((hit) => hit || (navigate ? cache.match(SHELL) : null)),
      )
      .then((hit) => hit || fetch(request)),
  );
});
`,
);

console.log(`Wrote dist/sw.js: ${files.length} files in ${CACHE}`);
