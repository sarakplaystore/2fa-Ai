import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import {
  headersFor,
  matchSource,
  relaxFraming,
  resolveRequest,
} from "../scripts/vercel-preview.mjs";

const read = (path) => readFileSync(new URL(path, import.meta.url), "utf8");
const config = JSON.parse(read("../vercel.json"));
const pkg = JSON.parse(read("../package.json"));
const html = read("../index.html");
const viteConfig = (await import("../vite.config.js")).default;

const SECURITY_HEADERS = [
  "Content-Security-Policy",
  "Strict-Transport-Security",
  "X-Content-Type-Options",
  "X-Frame-Options",
  "Referrer-Policy",
  "Cross-Origin-Opener-Policy",
  "Cross-Origin-Resource-Policy",
  "Permissions-Policy",
  "X-Robots-Tag",
];

// Splits a policy into a map of directive -> sources.
const policy = (value) =>
  new Map(
    value
      .split(";")
      .map((part) => part.trim().split(/\s+/))
      .filter(([name]) => name)
      .map(([name, ...sources]) => [name.toLowerCase(), sources]),
  );

test("vercel.json runs the same build the repository documents", () => {
  assert.equal(config.framework, "vite");
  assert.equal(config.installCommand, "npm ci");
  assert.equal(config.buildCommand, "npm run build");
  assert.equal(config.outputDirectory, "dist");
  assert.equal(
    config.outputDirectory,
    viteConfig.build?.outDir ?? "dist",
    "the deployment output directory must match Vite's build.outDir",
  );
  const script = /^npm run (\S+)$/.exec(config.buildCommand)[1];
  assert.ok(pkg.scripts[script], `${config.buildCommand} must exist in package.json`);
  assert.match(pkg.scripts[script], /vite build/);
  assert.match(
    pkg.scripts[script],
    /node scripts\/service-worker\.js/,
    "the service worker must be generated by the same command Vercel runs",
  );
});

test("the deployment runs a Node.js version Vite 7 supports", () => {
  const [major, minor] = pkg.engines.node.replace(/[^0-9.]/g, "").split(".").map(Number);
  assert.ok(
    major > 22 || (major === 22 && minor >= 12),
    "engines.node must stay at or above Vite's 22.12 floor",
  );
  const [runMajor, runMinor] = process.versions.node.split(".").map(Number);
  assert.ok(
    runMajor > major || (runMajor === major && runMinor >= (minor || 0)),
    `tests are running on Node ${process.versions.node}, below package.json's floor`,
  );
});

test("the SPA fallback serves deep links and keeps Vercel's own namespace", () => {
  assert.equal(config.rewrites.length, 1);
  const { source, destination } = config.rewrites[0];
  assert.equal(destination, "/index.html");
  for (const pathname of ["/", "/accounts", "/accounts/example/backup"])
    assert.ok(matchSource(source, pathname), `${pathname} should reach the app`);
  for (const pathname of [
    "/_vercel/insights/script.js",
    "/_vercel/speed-insights/script.js",
  ])
    assert.ok(
      !matchSource(source, pathname),
      `${pathname} is a Vercel endpoint and must not be rewritten to the app`,
    );
});

test("requests resolve like Vercel: filesystem, then rewrites, then 404", () => {
  const files = new Set(["/index.html", "/sw.js", "/assets/index-a.js", "/favicon.svg"]);
  const fileFor = (pathname) => (files.has(pathname) ? "/dist" + pathname : null);
  assert.deepEqual(resolveRequest(config, "/assets/index-a.js", fileFor), {
    kind: "file",
    file: "/dist/assets/index-a.js",
  });
  const deep = resolveRequest(config, "/accounts/example", fileFor);
  assert.equal(deep.kind, "rewrite");
  assert.equal(deep.file, "/dist/index.html");
  assert.equal(
    resolveRequest(config, "/_vercel/insights/script.js", fileFor).kind,
    "not-found",
  );
});

test("every response carries the security headers", () => {
  for (const pathname of [
    "/",
    "/index.html",
    "/sw.js",
    "/assets/index-a.js",
    "/accounts/example",
    "/missing.png",
  ]) {
    const headers = headersFor(config, pathname);
    for (const key of SECURITY_HEADERS)
      assert.ok(
        headers.has(key.toLowerCase()),
        `${pathname} is missing ${key}`,
      );
  }
  const headers = headersFor(config, "/");
  assert.equal(headers.get("x-frame-options").value, "DENY");
  assert.match(headers.get("strict-transport-security").value, /max-age=\d{7,}/);
  const permissions = headers.get("permissions-policy").value;
  assert.match(permissions, /camera=\(\)/);
  assert.match(permissions, /microphone=\(\)/);
  assert.match(permissions, /geolocation=\(\)/);
  // Device verification is delegated to the platform authenticator; it stays
  // allowed for this origin only.
  for (const feature of ["publickey-credentials-create", "publickey-credentials-get"])
    assert.match(permissions, new RegExp(`${feature}=\\(self\\)`));
});

test("the served CSP keeps every source the meta CSP requires", () => {
  const meta = /http-equiv="Content-Security-Policy"\s+content="([^"]+)"/.exec(html);
  assert.ok(meta, "index.html should declare a CSP meta tag");
  const declared = policy(meta[1]);
  assert.ok(declared.size > 0);
  const served = policy(
    headersFor(config, "/").get("content-security-policy").value,
  );
  // Both policies are enforced, and the effective policy is the stricter one,
  // so the header must not drop anything the page needs.
  for (const [name, sources] of declared) {
    assert.ok(served.has(name), `served CSP is missing ${name}`);
    for (const source of sources)
      assert.ok(
        served.get(name).includes(source),
        `served CSP is missing ${name} ${source}`,
      );
  }
  // frame-ancestors is ignored in a meta tag, so the header is the only place
  // it can be set.
  assert.ok(!declared.has("frame-ancestors"));
  assert.deepEqual(served.get("frame-ancestors"), ["'none'"]);
});

test("the local preview drops only the anti-framing headers by default", () => {
  const served = headersFor(config, "/");
  const relaxed = relaxFraming(served);
  assert.equal(relaxed["X-Frame-Options"], undefined);
  assert.ok(!/frame-ancestors/i.test(relaxed["Content-Security-Policy"]));
  // Everything else survives, so the preview still shows the deployed policy.
  assert.equal(
    served.get("x-frame-options").value,
    "DENY",
    "the deployment itself must keep denying framing",
  );
  for (const key of SECURITY_HEADERS.filter((k) => k !== "X-Frame-Options"))
    assert.ok(relaxed[key], `${key} should survive the preview relaxation`);
  assert.match(relaxed["Content-Security-Policy"], /default-src 'self'/);
  assert.match(relaxed["Cache-Control"], /max-age=0, must-revalidate/);
});

test("header rules are ordered general to specific, because the last match wins", () => {
  assert.equal(config.headers[0].source, "/(.*)");
  const cacheFor = (pathname) =>
    headersFor(config, pathname).get("cache-control")?.value;
  assert.match(cacheFor("/assets/index-a.js"), /max-age=31536000, immutable/);
  for (const pathname of ["/", "/index.html", "/sw.js"])
    assert.match(
      cacheFor(pathname),
      /max-age=0, must-revalidate/,
      `${pathname} must be revalidated so a new deployment is picked up`,
    );
  // A rewritten deep link is a request for the deep link, not for
  // /index.html, so the catch-all applies and Vercel's static default is used.
  assert.equal(cacheFor("/accounts/example"), undefined);
});

test("the generated service worker invalidates its cache on every new build", () => {
  const swScript = fileURLToPath(
    new URL("../scripts/service-worker.js", import.meta.url),
  );
  const build = (indexHtml) => {
    const dir = mkdtempSync(join(tmpdir(), "still-sw-"));
    mkdirSync(join(dir, "dist/assets"), { recursive: true });
    writeFileSync(join(dir, "dist/index.html"), indexHtml);
    writeFileSync(join(dir, "dist/assets/index-a.js"), "");
    execFileSync(process.execPath, [swScript], { cwd: dir });
    return readFileSync(join(dir, "dist/sw.js"), "utf8");
  };
  const first = build("<!doctype html><p>one</p>");
  const second = build("<!doctype html><p>two</p>");
  assert.match(first, /"\/assets\/index-a\.js"/);
  const cacheName = (sw) => /const CACHE = "([^"]+)"/.exec(sw)?.[1];
  assert.match(cacheName(first), /^still-/, "the cache must be named for the build");
  assert.equal(cacheName(first), cacheName(build("<!doctype html><p>one</p>")));
  assert.notEqual(
    cacheName(first),
    cacheName(second),
    "a new build must replace the previous cache",
  );
});

test(".vercelignore hides nothing the deployment needs", () => {
  const ignored = read("../.vercelignore")
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("#"));
  assert.ok(ignored.length > 0);
  for (const entry of ignored) {
    const path = entry.replace(/\/$/, "");
    for (const needed of [
      "package.json",
      "package-lock.json",
      "vercel.json",
      "index.html",
      "vite.config.js",
      "src/main.js",
      "public/favicon.svg",
      "public/manifest.webmanifest",
      "public/icons/icon-512.png",
      "scripts/service-worker.js",
    ])
      assert.ok(
        needed !== path && !needed.startsWith(path + "/"),
        `${entry} would keep ${needed} out of the build`,
      );
  }
});
